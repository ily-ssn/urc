import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
const base=await readFile('tests/database.mjs','utf8');
await db.exec(base.match(/await db.exec\(\s*`([\s\S]*?)`,\s*\);/)[1]);
const setup=await readFile('supabase/SETUP.sql','utf8');
await db.exec(setup);
const before=await db.query('SELECT count(*)::integer AS count FROM public.urc_entries');
assert.ok(before.rows[0].count>=3);
await db.exec(setup);
const after=await db.query('SELECT count(*)::integer AS count FROM public.urc_entries');
assert.equal(after.rows[0].count,before.rows[0].count);
const reset=(await db.query("SELECT published_snapshot FROM public.urc_entries WHERE kind='event' AND slug='reset'")).rows[0];
assert.equal(reset.published_snapshot.title,'The Reset');
assert.equal(reset.published_snapshot.payload.registration,'coming-soon');
const id='11111111-1111-4111-8111-111111111111';
await db.exec('ALTER TABLE auth.users ADD COLUMN email text');
await db.query('INSERT INTO auth.users(id,email)VALUES($1,$2)',[id,'owner@example.test']);
await db.exec((await readFile('supabase/OWNER.sql','utf8')).replaceAll('YOUR_OWNER_EMAIL','owner@example.test'));
assert.equal((await db.query('SELECT role FROM public.urc_team WHERE user_id=$1',[id])).rows[0].role,'owner');
await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[id]);
await db.exec('SET ROLE authenticated');
const path=id+'/aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa.webp';
const row=(await db.query("INSERT INTO public.urc_entries(kind,title,slug,payload,publish_requested)VALUES('page','Private picture','private-picture',$1,false)RETURNING id",[{heroPath:path}])).rows[0];
await db.query("INSERT INTO storage.objects(bucket_id,name)VALUES('urc-media',$1)",[path]);
await db.exec('RESET ROLE; SET ROLE anon');
assert.equal((await db.query('SELECT name FROM storage.objects WHERE name=$1',[path])).rows.length,0);
await db.exec('RESET ROLE; SET ROLE authenticated');
await db.query('UPDATE public.urc_entries SET revision=revision+1,publish_requested=true WHERE id=$1',[row.id]);
await db.exec('RESET ROLE; SET ROLE anon');
assert.equal((await db.query('SELECT name FROM storage.objects WHERE name=$1',[path])).rows.length,1);
await db.exec('RESET ROLE');
await db.close();
console.log('PASS: setup installs and reruns without overwriting content; owner bootstrap works; unpublished image is private and published banner becomes readable; seeded reservations remain closed.');
